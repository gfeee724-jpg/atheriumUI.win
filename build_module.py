"""Build VibeUI.lua (standalone module) from vibe_hub.lua (single-file demo).

The engine is everything up to the demo marker; the demo chunk stays behind
so vibe_hub.lua remains a one-file, loadstring-ready example.

Usage: python build_module.py [--check]
"""

import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "vibe_hub.lua")
DST = os.path.join(HERE, "VibeUI.lua")
MARKER = "--// ================= DEMO ================="

CHECK_DIR = os.path.join(os.environ.get("TEMP", "."), "opencode")
CHECKERS = ["balcheck.py", "luablocks.py"]


def build():
    with open(SRC, encoding="utf-8") as f:
        src = f.read()

    idx = src.find(MARKER)
    if idx == -1:
        raise SystemExit("demo marker not found: " + MARKER)

    engine = src[:idx].rstrip() + "\n"

    m = re.search(r'VibeUI\.Version\s*=\s*"([^"]+)"', engine)
    version = m.group(1) if m else "dev"

    banner = (
        "--// VibeUI v{0} | standalone UI module\n"
        "--// Generated by build_module.py from vibe_hub.lua - do not edit by hand.\n"
        "--//\n"
        "--//   local VibeUI = loadstring(readfile(\"VibeUI.lua\"))()\n"
        "--//   local win = VibeUI:CreateWindow({{ Title = \"My Hub\" }})\n"
        "--//\n"
        "\n"
    ).format(version)

    # drop the demo header line from the engine, keep the rest untouched
    first_nl = engine.find("\n")
    body = engine[first_nl + 1:] if engine.startswith("--//") else engine

    out = banner + body.rstrip() + "\n\nreturn VibeUI\n"

    with open(DST, "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print("wrote %s (v%s, %d lines)" % (os.path.basename(DST), version, out.count("\n")))


def check():
    ran = False
    for name in CHECKERS:
        path = os.path.join(CHECK_DIR, name)
        if not os.path.isfile(path):
            continue
        ran = True
        r = subprocess.run([sys.executable, path, DST], capture_output=True, text=True)
        print("%s: %s" % (name, (r.stdout or r.stderr).strip()))
        if r.returncode != 0:
            raise SystemExit(1)
    if not ran:
        print("checkers not found, skipped")


if __name__ == "__main__":
    build()
    if "--check" in sys.argv:
        check()
